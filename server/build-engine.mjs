// Builds src/engine.gen.js: a game table for the server. The rules are not copied by hand: they are cut out of
// www/index.html (between the "@engine-begin" / "@engine-end" marks), so the game on a phone and on the server
// always play by the same code. Around them go src/table-pre.js (what the rules expect to find) and
// src/table-post.js (the room: who sits, who watches, the owner's commands, keeping the game in storage).
// Runs by itself before every "wrangler deploy" / "wrangler dev" (see wrangler.toml).
import { readFileSync, writeFileSync } from 'node:fs';

const page = readFileSync(new URL('../www/index.html', import.meta.url), 'utf8');
const cut = n => {
  const a = page.indexOf(`// @engine-begin(${n})`), b = page.indexOf(`// @engine-end(${n})`);
  if (a < 0 || b < a) throw new Error(`engine marks (${n}) not found in www/index.html`);
  return page.slice(page.indexOf('\n', a) + 1, b);
};
const num = name => {
  const m = new RegExp(`const ${name} = (\\d+);`).exec(page);
  if (!m) throw new Error(name + ' not found in www/index.html');
  return +m[1];
};
const pre = readFileSync(new URL('./src/table-pre.js', import.meta.url), 'utf8');
const post = readFileSync(new URL('./src/table-post.js', import.meta.url), 'utf8');

const out = `// GENERATED by build-engine.mjs from www/index.html and src/table-*.js — do not edit by hand.
export const VERSION = ${num('VERSION')}, PROTO = ${num('PROTO')};
export function makeTable(H, init) {
${pre}
// ---------------- from www/index.html ----------------
${cut(1)}
${cut(2)}
// ---------------- the room ----------------
${post}
}
`;
writeFileSync(new URL('./src/engine.gen.js', import.meta.url), out);
console.log('engine.gen.js: ' + out.length + ' bytes');
